#!/usr/bin/env python3
"""Generate browser/additions/camoucfg/FontAliasesLinux.hpp (#325).

fontconfig answers a Linux identity's named lookups through the aliases in
browser/bundle/fontconfig/linux/fonts.conf: Helvetica becomes Nimbus Sans,
Arial becomes Arimo and then Liberation Sans. DirectWrite and CoreText have no
fontconfig, so a Linux claim on a Windows or macOS host would draw the flat
package's Apple and Microsoft faces for those names instead. The header is the
conf's answer, written down once, for the browser to apply.

The chain for a name is read the way gfxFcPlatformFontList::FindAndAddFamiliesLocked
reads it: FcConfigSubstitute on the pattern [name, sentinel], every family
before the sentinel (gfxFcPlatformFontList.cpp:2564-2608 at
FIREFOX_158_0_1_RELEASE). Only names the Linux fonts.json pool can report and
that no Linux face carries are listed; each target must be a family the
Linux groups ship.

Needs a Linux machine with fontconfig and a staged bundle (fonts/ and
fontconfig/linux/ beside camoufox-bin):

    python3 browser/scripts/gen-font-aliases.py --bin-dir dist/bin
    python3 browser/scripts/gen-font-aliases.py --bin-dir dist/bin --check

--check compares the header with what the bundle produces and exits non-zero
on any difference.
"""

import argparse
import difflib
import importlib.util
import json
import os
import re
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
HEADER = REPO / "browser" / "additions" / "camoucfg" / "FontAliasesLinux.hpp"
SENTINEL = "zzcamousentinel"

_spec = importlib.util.spec_from_file_location("verify_fonts", HERE / "verify-fonts.py")
verify_fonts = importlib.util.module_from_spec(_spec)
sys.path.insert(0, str(HERE))
_spec.loader.exec_module(verify_fonts)


def families(conf, *args):
    """Lowercased family names printed one per line by an fc-* tool."""
    out = verify_fonts.fc([*args], conf)
    return [fam.strip().lower() for line in out.splitlines() for fam in line.split(",") if fam.strip()]


def substituted(conf, name):
    """The families fontconfig puts in front of the sentinel for `name`, name first."""
    pattern = f"{verify_fonts.fc_pattern(name)},{SENTINEL}"
    chain = families(conf, "fc-pattern", "-c", "-f", "[%{family}\n]", pattern)
    if SENTINEL not in chain:
        raise SystemExit(f"fontconfig dropped the sentinel from {pattern!r}: {chain}")
    return chain[: chain.index(SENTINEL)]


def build(bin_dir):
    sys.path.insert(0, str(REPO / "python" / "src"))
    from camoufox.utils import _generate_fontconfig

    bin_dir = Path(bin_dir).resolve()
    conf = _generate_fontconfig(str(bin_dir / "fontconfig" / "linux"), path=bin_dir / "camoufox-bin", os_dir="linux")

    shipped = set(families(conf, "fc-list", "--format", "%{family}\n"))
    # Firefox's own files sit directly in fonts/ and are not on the conf's list.
    for font in sorted((bin_dir / "fonts").glob("*.[to]tf")):
        shipped.update(families(conf, "fc-scan", "--format", "%{family}\n", str(font)))
    if SENTINEL in shipped:
        raise SystemExit("the sentinel is a real family")

    pool = json.loads((REPO / "python" / "src" / "camoufox" / "fonts.json").read_text(encoding="utf-8"))["lin"]
    table = {}
    for name in sorted({n.lower() for n in pool}):
        if name in shipped:
            continue
        chain = substituted(conf, name)
        targets = list(dict.fromkeys(f for f in chain[1:] if f in shipped))
        table[name] = targets
    keys = set(table)
    clash = sorted(t for targets in table.values() for t in targets if t in keys)
    if clash:
        raise SystemExit(f"alias targets that are alias keys themselves would re-enter the rewrite: {clash}")

    makefile = (REPO / "browser" / "Makefile").read_text(encoding="utf-8")
    for package in ("package-windows", "package-macos"):
        recipe = re.search(rf"^{package}:.*\n((?:\t.*\n)+)", makefile, re.M)
        fonts = re.search(r"--fonts ([^\\\n]+)", recipe.group(1)) if recipe else None
        if not fonts or "linux" not in fonts.group(1).split():
            raise SystemExit(f"{package} does not bundle the Linux font groups, so the alias targets would not ship")
    return render(table)


def render(table):
    lines = [
        "// Generated by browser/scripts/gen-font-aliases.py from browser/bundle/fontconfig/linux/fonts.conf",
        "// and the Linux font groups; do not edit. Keys and targets are font-list keys (lowercase).",
        "// Each key is a name a Linux identity can report that no Linux face carries; its targets",
        "// are the Linux faces fontconfig substitutes for it, in preference order.",
        "#pragma once",
        "",
        "namespace mozilla {",
        "",
        "struct CamouFontAlias {",
        "  const char* name;",
        "  const char* const* targets;  // nullptr-terminated",
        "};",
        "",
    ]
    entries = []
    for i, (name, targets) in enumerate(table.items()):
        body = ", ".join(json.dumps(t) for t in targets + [None]).replace("null", "nullptr")
        lines.append(f"static const char* const kCamouAliasTargets{i}[] = {{{body}}};")
        entries.append(f"    {{{json.dumps(name)}, kCamouAliasTargets{i}}},")
    lines += ["", "static const CamouFontAlias kCamouLinuxAliases[] = {", *entries, "    {nullptr, nullptr}};", "", "}  // namespace mozilla", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--bin-dir", required=True, help="a staged browser directory: fonts/, fontconfig/linux/, camoufox-bin")
    ap.add_argument("--check", action="store_true", help="compare with the committed header instead of writing it")
    ap.add_argument("--out", default=str(HEADER))
    args = ap.parse_args()
    if not sys.platform.startswith("linux"):
        raise SystemExit("run on Linux: the table is fontconfig's answer for the Linux groups")
    text = build(args.bin_dir)
    if args.check:
        have = Path(args.out).read_text(encoding="utf-8")
        if have != text:
            tmp = Path(tempfile.mkdtemp()) / "FontAliasesLinux.hpp"
            tmp.write_text(text, encoding="utf-8")
            diff = "".join(difflib.unified_diff(have.splitlines(True), text.splitlines(True), "committed", "bundle"))
            raise SystemExit(f"{args.out} differs from what the bundle produces; regenerate it (fresh copy: {tmp})\n{diff}")
        print(f"{args.out} matches the bundle ({len(text.splitlines())} lines)")
        return
    Path(args.out).write_text(text, encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
